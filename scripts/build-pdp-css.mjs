// Build src/app/products/[handle]/pdp-source.css from the source rules that apply to the product page.
// Input (private, Git-ignored): reference/css/pdp/used-rules.css and root-vars.json, captured from the live source PDP by
// reference/scripts/r255-used-rules.mjs and r255-root-vars.mjs (ego-browser, 2026-11-06 snapshot).
// Scoping and de-duplication: scripts/lib/scoped-css.mjs (wrapper `.template-product`, the source body class).
import { readFileSync, writeFileSync } from "node:fs";
import { buildScopedCss } from "./lib/scoped-css.mjs";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const SCOPE = ".template-product";
const { css, ...stats } = buildScopedCss({
  used: readFileSync(`${ROOT}reference/css/pdp/used-rules.css`, "utf8"),
  vars: JSON.parse(readFileSync(`${ROOT}reference/css/pdp/root-vars.json`, "utf8")).vars,
  scope: SCOPE,
  // Rules written by vendor widgets the clone does not reproduce (Swym remind-me bars, Hulk spinner, Discounty).
  dropSheets: /^(inline:hulk-fb-spinner-css|inline:discounty-global-styles|announcement-bar\.css)$/,
  // PhotoSwipe lightbox: its state classes only exist while open, so the live-page extraction cannot see those rules.
  wholeSheets: { "photoswipe.css": `${ROOT}reference/css/pdp/photoswipe.css` },
  header: [
    "/* GENERATED by scripts/build-pdp-css.mjs from the source product-page rules (snapshot 2026-11-06). Do not edit by hand:",
    "   change the generator or add overrides to product-page.css. Selectors keep the source class names and are scoped to",
    `   the page wrapper ${SCOPE} with :where(), so specificity matches the source. */`,
  ],
});
writeFileSync(`${ROOT}src/app/products/[handle]/pdp-source.css`, css);
console.log(JSON.stringify(stats));
