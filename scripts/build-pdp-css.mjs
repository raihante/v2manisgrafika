// Build src/app/products/[handle]/pdp-source.css from the source rules that apply to the product page.
// Input (private, Git-ignored): reference/css/pdp/used-rules.css and root-vars.json, captured from the live source PDP by
// reference/scripts/r255-used-rules.mjs and r255-root-vars.mjs (ego-browser, 2026-11-06 snapshot).
// Every selector is scoped to the page wrapper `.template-product` (the source body class) with :where(), so specificity
// is unchanged and the rules cannot leak into the shared header, footer or other routes. Duplicate rules (the source
// loads product.css and product-grid.css twice) keep their LAST position, which preserves the source cascade.
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const used = readFileSync(`${ROOT}reference/css/pdp/used-rules.css`, "utf8");
const vars = JSON.parse(readFileSync(`${ROOT}reference/css/pdp/root-vars.json`, "utf8"));
const SCOPE = ".template-product";

// Rules written by vendor widgets the clone does not reproduce (Swym remind-me bars, Hulk spinner, Discounty).
const DROP_SHEETS = /^(inline:hulk-fb-spinner-css|inline:discounty-global-styles|announcement-bar\.css)$/;

const scopeSelector = (sel) =>
  sel.split(/,(?![^()]*\))/).map((s) => {
    s = s.trim();
    // `body.x .y` / `html .y`: the wrapper stands in for body (it carries the source body classes).
    const m = s.match(/^(html[^\s>]*\s*>?\s*)?body([^\s>]*)\s*(>?)\s*(.*)$/);
    if (m) return m[4] ? `${SCOPE}${m[2]} ${m[3] ? "> " : ""}${m[4]}` : `${SCOPE}${m[2]}`;
    if (/^html\b/.test(s)) s = s.replace(/^html[^\s]*\s+/, "");
    return `:where(${SCOPE}) ${s}`;
  }).join(", ");

// Stylesheets of stateful components included whole (their state classes only exist while open, so the live-page
// extraction cannot see those rules): PhotoSwipe lightbox. Minified source -> one rule per line, @media kept inline.
const WHOLE_SHEETS = { "photoswipe.css": `${ROOT}reference/css/pdp/photoswipe.css` };
function splitRules(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const out = [];
  let depth = 0, start = 0, media = null;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === "{") {
      if (depth === 0 && css.slice(start, i).trim().startsWith("@media")) { media = css.slice(start, i).trim(); start = i + 1; }
      depth++;
    } else if (c === "}") {
      depth--;
      if (media && depth === 1) { out.push(`${media} { ${css.slice(start, i + 1).trim()} }`); start = i + 1; }
      else if (media && depth === 0) { media = null; start = i + 1; }
      else if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; }
    }
  }
  return out.filter(Boolean);
}

const entries = [];
let sheet = "";
const emittedWhole = new Set();
for (const line of used.split("\n")) {
  const head = line.match(/^\/\* ===== (.+) ===== \*\/$/);
  if (head) {
    sheet = head[1];
    if (WHOLE_SHEETS[sheet] && !emittedWhole.has(sheet)) { emittedWhole.add(sheet); splitRules(readFileSync(WHOLE_SHEETS[sheet], "utf8")).forEach((l) => entries.push({ sheet, line: l })); }
    continue;
  }
  if (!line.trim() || DROP_SHEETS.test(sheet) || WHOLE_SHEETS[sheet]) continue;
  entries.push({ sheet, line });
}
// Keyframes span several lines in the input; re-join them.
const joined = [];
for (const e of entries) {
  const prev = joined[joined.length - 1];
  if (prev && prev.open > 0) { prev.line += "\n" + e.line; prev.open += (e.line.match(/{/g) || []).length - (e.line.match(/}/g) || []).length; continue; }
  joined.push({ ...e, open: (e.line.match(/{/g) || []).length - (e.line.match(/}/g) || []).length });
}

// Keep only keyframes that a kept rule animates (the extractor lists every @keyframes of every sheet).
// @-webkit-keyframes counts too: Chrome treats it as the same name, and the later definition wins.
const isKf = (l) => /^@(-webkit-)?keyframes\s/.test(l);
const animated = new Set(joined.filter((e) => !isKf(e.line))
  .flatMap((e) => [...e.line.matchAll(/animation(?:-name)?:\s*([^;}]+)/g)].flatMap((m) => m[1].split(/[\s,]+/))));
const out = [];
const seen = new Map();
for (const { sheet, line } of joined) {
  let text;
  if (isKf(line)) { if (!animated.has(line.match(/^@(?:-webkit-)?keyframes\s+([\w-]+)/)[1])) continue; text = line; }
  else {
    const media = line.match(/^((?:@(?:media|supports)[^{]+)+)\{ (.*) \}$/);
    const [chain, rule] = media ? [media[1].trim(), media[2]] : ["", line];
    const i = rule.indexOf("{");
    const body = `${scopeSelector(rule.slice(0, i))}${rule.slice(i)}`;
    text = chain ? chain.split(/ (?=@)/).reduceRight((acc, c) => `${c} { ${acc} }`, body) : body;
  }
  if (seen.has(text)) out[seen.get(text)] = null;
  seen.set(text, out.length);
  out.push({ sheet, text });
}

const lines = [
  "/* GENERATED by scripts/build-pdp-css.mjs from the source product-page rules (snapshot 2026-11-06). Do not edit by hand:",
  "   change the generator or add overrides to product-page.css. Selectors keep the source class names and are scoped to",
  `   the page wrapper ${SCOPE} with :where(), so specificity matches the source. */`,
  `${SCOPE}{${Object.entries(vars.vars).map(([k, v]) => `${k}:${v}`).join(";")}}`,
];
let last = "";
for (const e of out) {
  if (!e) continue;
  if (e.sheet !== last) { lines.push(`\n/* --- ${e.sheet} --- */`); last = e.sheet; }
  lines.push(e.text);
}
writeFileSync(`${ROOT}src/app/products/[handle]/pdp-source.css`, lines.join("\n") + "\n");
console.log(JSON.stringify({ rules: out.filter(Boolean).length, dropped: out.filter((e) => !e).length, bytes: lines.join("\n").length }));
