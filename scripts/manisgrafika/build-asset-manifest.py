"""Append the missing Manis Grafika asset rows to docs/asset-manifest.md (round 277, rebrand step 6 "full manifest pass").

Every file under public/assets/manisgrafika/ whose local path is not yet in the manifest gets a row: source URL and
hashes from the private download record reference/manisgrafika/2026-11-16/assets.json (computed locally for files that
are not in it), dimensions, bytes, and usage found by searching src/ (product handles for the catalog fixture, file
names for the other fixtures and code). Files referenced nowhere are listed as "unused". Re-running replaces the section.
Run: python scripts/manisgrafika/build-asset-manifest.py
"""
import hashlib, json, re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "docs/asset-manifest.md"
HEAD = "## Manis Grafika catalog and remaining photos (round 277, 2026-11-19)"
record = {a["local"]: a for a in json.loads((ROOT / "reference/manisgrafika/2026-11-16/assets.json").read_text(encoding="utf-8"))}

text = MANIFEST.read_text(encoding="utf-8")
if HEAD in text:
    text = text[: text.index(HEAD)].rstrip() + "\n"
listed = set(re.findall(r"`(/assets/manisgrafika/[^`]+)`", text))

products = json.loads((ROOT / "src/data/product-details.json").read_text(encoding="utf-8"))
products = products if isinstance(products, list) else list(products.values())
sources = {p.relative_to(ROOT).as_posix(): p.read_text(encoding="utf-8") for p in (ROOT / "src").rglob("*") if p.suffix in {".json", ".ts", ".tsx", ".css"} and p.name != "product-details.json"}


def usage(local: str) -> str:
    handles = [p.get("handle", "?") for p in products if local in json.dumps(p)]
    files = [name.removeprefix("src/") for name, body in sources.items() if local in body]
    parts = []
    if handles:
        parts.append("PDP " + ", ".join(sorted(set(handles))))
    if files:
        parts.append(", ".join(sorted(files)))
    return "; ".join(parts) or "unused (downloaded, not referenced)"


rows, unused = [], 0
for path in sorted((ROOT / "public/assets/manisgrafika").rglob("*")):
    if not path.is_file():
        continue
    local = "/" + path.relative_to(ROOT / "public").as_posix()
    if local in listed:
        continue
    data = path.read_bytes()
    rec = record.get(local, {})
    sha = rec.get("sha256") or hashlib.sha256(data).hexdigest()
    try:
        with Image.open(path) as im:
            dims = f"{im.width}x{im.height}"
    except Exception:
        dims = "-"
    src = rec.get("source") or "agent-derived / see the build script of its folder"
    use = usage(local)
    unused += use.startswith("unused")
    rows.append(f"| `{local}` | {src} | `{sha[:16]}` | {dims} | {len(data)} | {use} |")

section = f"""
{HEAD}

Generated by `scripts/manisgrafika/build-asset-manifest.py` for every file under `public/assets/manisgrafika/` that the sections above do not list ({len(rows)} files, {unused} unused). Source, SHA-256 and bytes come from the private download record `reference/manisgrafika/2026-11-16/assets.json`; usage is a text search of `src/` (catalog photos: product handles in `src/data/product-details.json`). Authorization: manisgrafika.id is the Digitakarya-built client site, download owner-instructed (round 262).

| Local path | Source | SHA-256 (16) | Dimensions | Bytes | Usage |
|---|---|---|---:|---:|---|
""" + "\n".join(rows) + "\n"
MANIFEST.write_text(text + section, encoding="utf-8", newline="\n")
print(f"rows {len(rows)}, unused {unused}")
